export const formatHeaderDate = (d: Date = new Date(), lang: AppLanguage = 'ko'): string => {
  const month = d.getMonth() + 1;
  const day = d.getDate();
  const dayIndex = d.getDay();

  if (lang === 'en') {
    const days = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    return `${months[month - 1]} ${day}, ${days[dayIndex]}`;
  }

  if (lang === 'ja') {
    const days = ['日', '月', '火', '水', '木', '金', '土'];
    return `${month}月${day}日 (${days[dayIndex]}曜日)`;
  }

  const days = ['일', '월', '화', '수', '목', '금', '토'];
  return `${month}월 ${day}일 (${days[dayIndex]}요일)`;
};

export const getDayNamesForLanguage = (lang: AppLanguage = 'ko'): string[] => {
  switch (lang) {
    case 'en':
      return ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
    case 'ja':
      return ['日', '月', '火', '水', '木', '金', '土'];
    case 'ko':
    default:
      return ['일', '월', '화', '수', '목', '금', '토'];
  }
};

// React Context for Global Language state
interface LanguageContextType {
  language: AppLanguage;
  setLanguage: (lang: AppLanguage) => void;
  t: typeof translations['ko'];
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'ko',
  setLanguage: () => {},
  t: translations.ko,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    const saved = localStorage.getItem('morehabbit_lang') as AppLanguage;
    if (saved && ['ko', 'en', 'ja'].includes(saved)) {
      return saved;
    }
    return 'ko';
  });

  const setLanguage = (lang: AppLanguage) => {
    setLanguageState(lang);
    localStorage.setItem('morehabbit_lang', lang);
  };

  useEffect(() => {
    const handleStorage = (e: StorageEvent) => {
      if (e.key === 'morehabbit_lang' && e.newValue && ['ko', 'en', 'ja'].includes(e.newValue)) {
        setLanguageState(e.newValue as AppLanguage);
      }
    };
    window.addEventListener('storage', handleStorage);
    return () => window.removeEventListener('storage', handleStorage);
  }, []);

  const currentT = translations[language] || translations.ko;

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t: currentT }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
